export function packagePhoto(artwork: string, slug = ''): PhotoKey {
  // A few packages are better shown by the place they are named after.
  if (/murudeshwar/.test(slug)) return 'murudeshwar';
  if (/mirjan|kumta/.test(slug)) return 'mirjan-fort';
  if (/yana|vibhooti/.test(slug)) return 'yana';
  if (/temple/.test(slug)) return 'temple';
  return PACKAGE_PHOTO[artwork] ?? 'cliff-sea';
}

